local function map(lhs, rhs, desc)
    vim.keymap.set("n", lhs, rhs, { silent = true, desc = desc })
end
map("<leader>fw", "<cmd>write<cr>", "保存文件")
map("<leader>fr", "<cmd>edit<cr>", "重新读取")
map("<leader>bn", "<cmd>bnext<cr>", "下个缓冲区")
map("<leader>bp", "<cmd>bprevious<cr>", "上个缓冲区")
map("<leader>bd", "<cmd>bdelete<cr>", "关闭缓冲区")
map("<leader>wv", "<cmd>vsplit<cr>", "纵向分屏")
map("<leader>ws", "<cmd>split<cr>", "横向分屏")
map("<leader>wq", "<cmd>close<cr>", "关闭窗口")
map("<leader>we", "<C-w>=", "均分窗口")
map("<leader>ui", "<cmd>ConfigInfo<cr>", "有效配置")
map("<leader>uh", "<cmd>checkhealth config<cr>", "配置健康检查")
map("<leader>un", "<cmd>nohlsearch<cr>", "清除搜索高亮")
